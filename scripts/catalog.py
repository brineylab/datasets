"""Generate CATALOG.md from datasets/*/SKILL.md frontmatter and results/<name>/<version>.txt.

    python3 -I scripts/catalog.py              prints CATALOG.md to stdout
    python3 -I scripts/catalog.py --write      writes CATALOG.md at the repository root

The Hub org comes from hub.toml. Runs on Python 3.8 or later with the standard library alone.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

_HERE = str(Path(__file__).resolve().parent)
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)
import check  # noqa: E402


def _compact(value: int, units: tuple[str, ...], sep: str = "") -> str:
    if value < 1000:
        return f"{value}{sep}{units[0]}"
    n, idx = float(value), 0
    while n >= 1000 and idx < len(units) - 1:
        n /= 1000.0
        idx += 1
    if round(n, 0) >= 1000 and idx < len(units) - 1:
        n /= 1000.0
        idx += 1
    decimals = 2 if round(n, 2) < 10 else 1 if round(n, 1) < 100 else 0
    return f"{n:.{decimals}f}{sep}{units[idx]}"


def format_count(count: int, unit: str) -> str:
    return f"{_compact(count, ('', 'k', 'M', 'B', 'T'))} {unit}"


def format_bytes(size: int) -> str:
    return _compact(size, ("B", "KB", "MB", "GB", "TB"), sep=" ")


def escape_cell(text: str) -> str:
    return " ".join(text.split()).replace("|", r"\|")


def render_catalog(root: Path = check.ROOT) -> str:
    org = check.read_toml((root / "hub.toml").read_text(encoding="utf-8"))["org"]
    datasets_dir = root / "datasets"
    rows: list[str] = []
    for d in sorted(datasets_dir.iterdir()) if datasets_dir.is_dir() else []:
        if not d.is_dir():
            continue
        skill = d / "SKILL.md"
        if not skill.is_file():
            continue
        fm = check.frontmatter(skill)
        meta = fm.get("metadata")
        if not isinstance(meta, dict) or not meta.get("version"):
            continue
        name = d.name
        version = meta["version"]
        record_path = root / "results" / name / f"{version}.txt"
        if not record_path.is_file():
            continue
        rec = check.parse_record(record_path)
        if rec.get("exit") != 0:
            continue
        count, unit = meta.get("count", ""), meta.get("unit", "")
        entries = format_count(int(count), unit) if count.isdigit() and unit else "—"
        files = rec.get("files", [])
        size = format_bytes(sum(sz for _, sz, _ in files)) if files else "—"
        license_id = escape_cell(meta.get("license", "")) or "—"
        tools = escape_cell(meta.get("tools", "")) or "—"
        desc = escape_cell(fm.get("description", "")) or "—"
        rows.append(
            f"| [{name}](datasets/{name}/SKILL.md) "
            f"| [v{version}](https://huggingface.co/datasets/{org}/{name}/tree/v{version}) "
            f"| {entries} | {size} | {license_id} | {tools} | {desc} |"
        )
    noun = "dataset" if len(rows) == 1 else "datasets"
    lines = [
        "# Dataset Catalog",
        "",
        "<!-- Auto-generated by scripts/catalog.py. Do not edit by hand. -->",
        "",
        f"{len(rows)} published {noun}. Read any version with:",
        f'`snapshot_download("{org}/<name>", repo_type="dataset", revision="v<version>")`',
        "",
        "| Dataset | Version | Entries | Size | License | Tools | Description |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        *rows,
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--write", action="store_true", help="write CATALOG.md at the repository root")
    p.add_argument("--root", type=Path, default=check.ROOT, help="repository root directory")
    args = p.parse_args(argv)
    text = render_catalog(args.root)
    if args.write:
        (args.root / "CATALOG.md").write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
